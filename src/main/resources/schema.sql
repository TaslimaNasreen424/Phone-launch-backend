-- H2 Database Schema (For Testing with H2)
-- Note: Oracle version uses stored procedures, this uses direct SQL

-- Create PRODUCTS table
CREATE TABLE IF NOT EXISTS PRODUCTS (
    PRODUCT_ID BIGINT PRIMARY KEY,
    SKU VARCHAR(50) UNIQUE,
    MODEL_NAME VARCHAR(100),
    COLOR VARCHAR(50),
    STORAGE_GB INT,
    PRICE DECIMAL(10, 2),
    LAUNCH_DATE TIMESTAMP,
    CREATED_AT TIMESTAMP
);

-- Create INVENTORY table
CREATE TABLE IF NOT EXISTS INVENTORY (
    INVENTORY_ID BIGINT PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    TOTAL_UNITS BIGINT NOT NULL,
    AVAILABLE_UNITS BIGINT NOT NULL,
    RESERVED_UNITS BIGINT NOT NULL,
    SOLD_UNITS BIGINT NOT NULL,
    LAST_UPDATED TIMESTAMP,
    VERSION BIGINT DEFAULT 0,
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

-- Create RESERVATION table
CREATE TABLE IF NOT EXISTS RESERVATIONS (
    RESERVATION_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    PRODUCT_ID BIGINT NOT NULL,
    CUSTOMER_ID VARCHAR(100) NOT NULL,
    QUANTITY INT NOT NULL,
    STATUS VARCHAR(50),
    RESERVED_AT TIMESTAMP,
    EXPIRES_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    SESSION_TOKEN VARCHAR(255),
    DEVICE_FINGERPRINT VARCHAR(255),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

-- Create PURCHASE_HISTORY table
CREATE TABLE IF NOT EXISTS PURCHASE_HISTORY (
    PURCHASE_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    RESERVATION_ID BIGINT,
    PRODUCT_ID BIGINT NOT NULL,
    CUSTOMER_ID VARCHAR(100) NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE DECIMAL(10, 2),
    TOTAL_PRICE DECIMAL(10, 2),
    STATUS VARCHAR(50),
    PURCHASED_AT TIMESTAMP,
    FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATIONS(RESERVATION_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

